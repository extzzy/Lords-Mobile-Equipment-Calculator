const I18N_DEFAULT_LOCALE = 'ru';
const I18N_STORAGE_KEY = 'lords-locale';

let currentLocale = (() => {
  try {
    const saved = localStorage.getItem(I18N_STORAGE_KEY);
    if (saved && LOCALES[saved]) return saved;
  } catch (_) {}
  return I18N_DEFAULT_LOCALE;
})();

function t(key) {
  const dict = LOCALES[currentLocale] || LOCALES[I18N_DEFAULT_LOCALE];
  return dict[key] !== undefined ? dict[key] : key;
}

function setLocale(locale) {
  if (!LOCALES[locale]) return;
  currentLocale = locale;
  try { localStorage.setItem(I18N_STORAGE_KEY, locale); } catch (_) {}
  document.documentElement.lang = locale;
  applyStaticTranslations();
  // Триггерим событие — слушатели в app.js пересоберут динамический контент
  document.dispatchEvent(new CustomEvent('localechange', { detail: { locale } }));
}

function getLocale() {
  return currentLocale;
}

// Переводит все элементы со статическими data-i18n / data-i18n-title атрибутами
function applyStaticTranslations() {
  document.querySelectorAll('[data-i18n]').forEach(el => {
    el.textContent = t(el.dataset.i18n);
  });
  document.querySelectorAll('[data-i18n-title]').forEach(el => {
    const text = t(el.dataset.i18nTitle);
    el.setAttribute('title', text);
    el.dataset.titleBase = text;
  });
  document.querySelectorAll('[data-i18n-placeholder]').forEach(el => {
    el.setAttribute('placeholder', t(el.dataset.i18nPlaceholder));
  });
  // Заголовок страницы
  document.title = t('app.title');
}
